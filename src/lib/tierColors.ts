// Палитра цветов для тиров (выбор кнопками, надёжно на телефоне).
// Сначала оттенки серого (основа интерфейса), потом несколько спокойных цветов.
// Уже созданные тиры сохраняют свой цвет: поменять его можно в окне правки тира.
export const TIER_COLORS = [
  '#f4f4f4', // белый
  '#d4d4d4', // светло-серый
  '#a3a3a3', // серый
  '#737373', // тёмно-серый
  '#404040', // графит
  '#171717', // чёрный
  '#c0504d', // красный
  '#d98b3a', // оранжевый
  '#d9c04a', // жёлтый
  '#5b9a6a', // зелёный
  '#4f7fb8', // синий
  '#7b62a8', // фиолетовый
]

// Выбирает читаемый цвет текста (тёмный или белый) для фона заданного цвета
export function readableTextColor(hex: string): string {
  const value = hex.replace('#', '')
  const r = parseInt(value.slice(0, 2), 16)
  const g = parseInt(value.slice(2, 4), 16)
  const b = parseInt(value.slice(4, 6), 16)
  // Простая оценка яркости цвета (0..1)
  const luminance = (0.299 * r + 0.587 * g + 0.114 * b) / 255
  return luminance > 0.6 ? '#0f172a' : '#ffffff'
}
